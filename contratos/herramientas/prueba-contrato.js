const ganache = require('ganache'), { ethers } = require('ethers'), art = require('../TrazaAnclaje.json');
(async () => {
  const g = ganache.provider({ logging: { quiet: true }, chain: { hardfork: 'merge' }, wallet: { totalAccounts: 3 } });
  const prov = new ethers.BrowserProvider(g);
  const [dueno, otro] = await Promise.all([prov.getSigner(0), prov.getSigner(1)]);
  const f = new ethers.ContractFactory(art.abi, art.bytecode, dueno);
  const c = await f.deploy(); await c.waitForDeployment();
  const ok = (cond, msg) => { console.log((cond ? 'OK   ' : 'FALLA') + ' ' + msg); if (!cond) process.exitCode = 1; };
  ok(await c.propietario() === await dueno.getAddress(), 'propietario = quien despliega');
  ok(await c.autorizados(await dueno.getAddress()), 'propietario autorizado');
  const r1 = '0x' + 'ab'.repeat(32);
  const tx = await c.anclar(r1, 982); const rc = await tx.wait();
  ok(rc.status === 1, 'anclar 982 bloques');
  const ev = rc.logs.map(l => c.interface.parseLog(l)).find(e => e && e.name === 'Anclado');
  ok(ev && ev.args.raiz === r1 && ev.args.bloques === 982n, 'evento Anclado');
  const q = await c.consultar(r1);
  ok(q.bloques === 982n && q.cuando > 0n && q.quien === await dueno.getAddress(), 'consultar devuelve el anclaje');
  ok((await c.consultar('0x' + '11'.repeat(32))).cuando === 0n, 'huella no anclada => cuando 0');
  ok(await c.total() === 1n && await c.raices(0) === r1, 'total y raices');
  const sel = n => c.interface.getError(n).selector;
  const falla = async (p, nombre) => { try { await p; return false; } catch (e) { const m = JSON.stringify(e) + String(e.message) + JSON.stringify(e.info || {}); return (e.revert && e.revert.name) === nombre || m.includes(sel(nombre).slice(2)); } };
  ok(await falla(c.anclar(r1, 982), 'YaAnclado'), 'no se puede anclar dos veces la misma huella');
  ok(await falla(c.connect(otro).anclar('0x' + 'cd'.repeat(32), 5), 'NoAutorizado'), 'cuenta no autorizada no puede anclar');
  ok(await falla(c.anclar(ethers.ZeroHash, 5), 'DatosInvalidos'), 'huella vacía rechazada');
  ok(await falla(c.connect(otro).autorizar(await otro.getAddress(), true), 'NoAutorizado'), 'solo el propietario autoriza');
  await (await c.autorizar(await otro.getAddress(), true)).wait();
  const rc2 = await (await c.connect(otro).anclar('0x' + 'cd'.repeat(32), 983)).wait();
  ok(rc2.status === 1 && await c.total() === 2n, 'cuenta autorizada ancla');
  console.log('gas anclar ~', rc.gasUsed.toString());
})().catch(e => { console.error(e); process.exit(1); });
